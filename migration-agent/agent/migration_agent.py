    def _migrate_routing(
        self,
        scan: AngularProjectScan,
        system_prompt: str,
        writer: OutputWriter,
    ) -> MigrationResult:
        logger.info("Migrating routing: %s", scan.routing_file)
        start = time.monotonic()
        try:
            ts_source = scan.routing_file.read_text(encoding="utf-8")  # type: ignore[union-attr]
            context = "Components available:\n" + "\n".join(
                f"  - {c.name}" for c in scan.components
            )
            user_prompt = self._prompt_builder.build_routing_prompt(
                ts_source=ts_source,
                additional_context=context,
            )
            content = self._client.complete(system_prompt, user_prompt)  # type: ignore[union-attr]
            out_path = writer.write_app(content)
            return MigrationResult(
                source_file=str(scan.routing_file),
                output_file=str(out_path),
                file_type="Routing → App.tsx",
                success=True,
                duration_s=time.monotonic() - start,
            )
        except Exception as exc:
            logger.error("  ✗ Failed to migrate routing: %s", exc)
            return MigrationResult(
                source_file=str(scan.routing_file),
                output_file="",
                file_type="Routing → App.tsx",
                success=False,
                error=str(exc),
                duration_s=time.monotonic() - start,
            )

    def _migrate_environments(
        self,
        scan: AngularProjectScan,
        system_prompt: str,
        writer: OutputWriter,
    ) -> MigrationResult:
        env_path = scan.environment_files[0]
        logger.info("Migrating environment: %s", env_path)
        start = time.monotonic()
        try:
            ts_source = env_path.read_text(encoding="utf-8")
            user_prompt = self._prompt_builder.build_environment_prompt(ts_source)
            content = self._client.complete(system_prompt, user_prompt)  # type: ignore[union-attr]
            writer.write_env(content)
            return MigrationResult(
                source_file=str(env_path),
                output_file=".env.development / .env.production / src/config/env.ts",
                file_type="Environment",
                success=True,
                duration_s=time.monotonic() - start,
            )
        except Exception as exc:
            logger.error("  ✗ Failed to migrate environment: %s", exc)
            return MigrationResult(
                source_file=str(env_path),
                output_file="",
                file_type="Environment",
                success=False,
                error=str(exc),
                duration_s=time.monotonic() - start,
            )
